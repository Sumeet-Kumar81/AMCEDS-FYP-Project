"""Migration tests (B1-A1-06). They use their own throwaway database, created fresh and deleted after,
so they never touch the application database or ``dispatch_test``. Skipped with a reason if no
PostgreSQL server is reachable."""
from __future__ import annotations

import os
from collections.abc import Iterator
from pathlib import Path

import psycopg2
import pytest
from alembic import command
from alembic.config import Config
from alembic.script import ScriptDirectory
from psycopg2 import sql
from sqlalchemy.engine import make_url
from sqlalchemy.exc import DBAPIError

pytestmark = pytest.mark.db

BACKEND = Path(__file__).resolve().parents[2]
ALEMBIC_INI = BACKEND / "alembic.ini"
MIGRATION_DB = "dispatch_migrations_test"


def _admin_dsn(async_url: str) -> str:
    return make_url(async_url).set(drivername="postgresql", database="postgres").render_as_string(hide_password=False)


def _sync_dsn(async_url: str) -> str:
    return make_url(async_url).set(drivername="postgresql").render_as_string(hide_password=False)


def _recreate(admin_dsn: str, name: str, drop_only: bool = False) -> None:
    conn = psycopg2.connect(admin_dsn, connect_timeout=3)
    conn.autocommit = True
    try:
        with conn.cursor() as cur:
            cur.execute(sql.SQL("DROP DATABASE IF EXISTS {} WITH (FORCE)").format(sql.Identifier(name)))
            if not drop_only:
                cur.execute(sql.SQL("CREATE DATABASE {}").format(sql.Identifier(name)))
    finally:
        conn.close()


@pytest.fixture
def migration_db() -> Iterator[str]:
    """Async URL of a brand-new, empty database (no PostGIS yet)."""
    base = os.environ.get("DATABASE_URL")
    if not base:
        pytest.skip("no DATABASE_URL set; migration tests not run")
    url = make_url(base).set(database=MIGRATION_DB).render_as_string(hide_password=False)
    try:
        _recreate(_admin_dsn(url), MIGRATION_DB)
    except psycopg2.OperationalError as exc:
        pytest.skip(f"PostgreSQL not reachable ({exc.__class__.__name__}); migration tests not run")
    try:
        yield url
    finally:
        _recreate(_admin_dsn(url), MIGRATION_DB, drop_only=True)


def alembic_config(url: str) -> Config:
    cfg = Config(str(ALEMBIC_INI))
    cfg.attributes["database_url"] = url
    cfg.attributes["configure_logger"] = False  # keep pytest's logging setup
    return cfg


def query(url: str, statement: str) -> list[tuple]:
    conn = psycopg2.connect(_sync_dsn(url), connect_timeout=3)
    conn.autocommit = True
    try:
        with conn.cursor() as cur:
            cur.execute(statement)
            return cur.fetchall() if cur.description else []
    finally:
        conn.close()


def extensions(url: str) -> set[str]:
    return {row[0] for row in query(url, "SELECT extname FROM pg_extension")}


def current_revision(url: str) -> str | None:
    exists = query(url, "SELECT to_regclass('public.alembic_version')")[0][0]
    if exists is None:
        return None
    rows = query(url, "SELECT version_num FROM alembic_version")
    return rows[0][0] if rows else None


# ---------------------------------------------------------------- tests
def test_migration_chain_has_one_head_starting_at_0001() -> None:
    scripts = ScriptDirectory.from_config(Config(str(ALEMBIC_INI)))
    assert scripts.get_heads() == ["0001"]
    assert scripts.get_revision("0001").down_revision is None


def test_upgrade_downgrade_upgrade_is_clean(migration_db: str) -> None:
    cfg = alembic_config(migration_db)
    assert "postgis" not in extensions(migration_db)

    command.upgrade(cfg, "head")
    assert "postgis" in extensions(migration_db)
    assert current_revision(migration_db) == "0001"
    assert query(migration_db, "SELECT postgis_version()")[0][0]

    command.downgrade(cfg, "base")
    assert "postgis" not in extensions(migration_db)
    assert current_revision(migration_db) is None

    command.upgrade(cfg, "head")
    assert current_revision(migration_db) == "0001"


def test_models_and_database_have_no_differences(migration_db: str) -> None:
    """Autogenerate finds nothing to do: PostGIS's own tables are excluded correctly."""
    cfg = alembic_config(migration_db)
    command.upgrade(cfg, "head")
    command.check(cfg)  # raises AutogenerateDiffsDetected if a migration would be generated


def test_no_differences_on_a_database_set_up_like_the_postgis_image(migration_db: str) -> None:
    """Regression (found on the local database): the postgis/postgis image installs tiger/topology and
    sets search_path to include them. Autogenerate must still see no differences, i.e. never plan to
    drop the image's tiger tables."""
    query(migration_db, "CREATE EXTENSION IF NOT EXISTS postgis")
    query(migration_db, "CREATE EXTENSION IF NOT EXISTS postgis_topology")
    query(migration_db, "CREATE EXTENSION IF NOT EXISTS postgis_tiger_geocoder CASCADE")
    query(migration_db, f'ALTER DATABASE {MIGRATION_DB} SET search_path = "$user", public, topology, tiger')
    assert query(migration_db, "SHOW search_path")[0][0] == '"$user", public, topology, tiger'
    cfg = alembic_config(migration_db)
    command.upgrade(cfg, "head")
    command.check(cfg)


def test_downgrade_refuses_when_something_depends_on_postgis(migration_db: str) -> None:
    """No CASCADE: like the image's own database, a dependent extension makes the downgrade fail safely."""
    cfg = alembic_config(migration_db)
    command.upgrade(cfg, "head")
    query(migration_db, "CREATE EXTENSION postgis_topology")
    with pytest.raises(DBAPIError, match="depend"):
        command.downgrade(cfg, "base")
    assert {"postgis", "postgis_topology"} <= extensions(migration_db)
    assert current_revision(migration_db) == "0001"


def test_alembic_ini_holds_no_url_or_password() -> None:
    text = ALEMBIC_INI.read_text(encoding="utf-8")
    assert "sqlalchemy.url" not in text.replace("# ", "")
    assert "postgresql" not in text and "change_me" not in text
