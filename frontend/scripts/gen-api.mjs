#!/usr/bin/env node
// Generates shared/src/api/schema.ts from the running backend's /openapi.json (B1-A3-01).
//   npm run gen:api          write the file
//   npm run gen:api:check    fail (exit 1) if the file no longer matches the backend contract
// The API address comes from VITE_API_URL (default http://localhost:8000). Start the backend first.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const apiUrl = (process.env.VITE_API_URL || "http://localhost:8000").replace(/\/+$/, "");
const target = fileURLToPath(new URL("../shared/src/api/schema.ts", import.meta.url));
const check = process.argv.includes("--check");
const HEADER =
  "// GENERATED by `npm run gen:api` from the backend /openapi.json. Do not edit by hand.\n" +
  "// Regenerate whenever the API contract changes; `npm run gen:api:check` catches drift.\n\n";

let spec;
try {
  const res = await fetch(`${apiUrl}/openapi.json`);
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  spec = await res.json();
} catch (err) {
  console.error(`Could not read ${apiUrl}/openapi.json (${err.message}). Is the backend running?`);
  process.exit(2);
}

const output = HEADER + astToString(await openapiTS(spec));

if (check) {
  const current = await readFile(target, "utf8").catch(() => "");
  if (current !== output) {
    console.error("shared/src/api/schema.ts does not match the backend contract. Run: npm run gen:api");
    process.exit(1);
  }
  console.log("API types match the backend contract.");
} else {
  await writeFile(target, output);
  console.log(`Wrote ${target} from ${apiUrl}/openapi.json`);
}
